//! Native CUDA f64 solid arrangements shared by training mesh and width metrics.
//!
//! Numerical/topology code is adapted from pleochroma's MIT stone_metrics code;
//! see LICENSE-MIT. CUDA owns large pair/triple feasibility scans and tool-face
//! clipping. Host code preserves stable plane/vertex ordering, face rings,
//! calipers and dynamic concave edge visibility. Driver/numerical errors are
//! latched and returned; physical unbounded/degenerate outcomes are statuses.
use glam::DVec3;
use pleochroma::geometry::{
    stone_metrics::{SolidMetrics, SolidStatus},
    tool::ToolPrimitive,
};
#[cfg(feature = "cuda")]
use std::collections::VecDeque;
use std::{
    collections::BTreeMap,
    sync::{
        Arc, Mutex,
        atomic::{AtomicU64, Ordering},
    },
};

