/// Mesh, metrics and distinct planar vertices from one candidate arrangement.
#[derive(Debug, Clone)]
pub struct SolidResult {
    /// Closed mesh or the original degeneracy/unboundedness diagnostic.
    pub status: SolidStatus,
    /// Production physical measurements; carved meshes replace only volume.
    pub metrics: Option<SolidMetrics>,
    /// Distinct plane-arrangement vertices, in original coordinate units/order.
    pub vertices: Vec<DVec3>,
}

/// Cumulative workload, transfer, fallback and error counters for one run.
#[derive(Debug, Default, Clone, serde::Serialize)]
pub struct SolidDiagnostics {
    /// GPU plane arrangements (including physically rejected arrangements).
    pub cuda_arrangements: u64,
    /// Bounded lexicographic triple tiles processed on CUDA.
    pub cuda_tiles: u64,
    /// Plane triples covered by the GPU scans, before conservative pair pruning.
    pub candidate_triples: u64,
    /// Triple lanes actually launched after conservative GPU pair pruning.
    pub surviving_triples: u64,
    /// Feasible candidate vertices before stable position deduplication.
    pub feasible_candidates: u64,
    /// Device-to-host compacted vertices and metadata bytes.
    pub readback_bytes: u64,
    /// Upper bound on simultaneously retained device scratch for this service.
    pub peak_scratch_bytes: u64,
    /// Independent tool-face clipping batches actually launched.
    pub cuda_tool_face_batches: u64,
    /// Tool-face polygons generated by CUDA.
    pub cuda_tool_faces: u64,
    /// Exact tool polytope cache hits (four entries maximum).
    pub tool_face_cache_hits: u64,
    /// Width requests served by exact input-bit cached measurements.
    pub width_cache_hits: u64,
    /// Concave candidates whose dynamic splitting/edge visibility ran on CPU.
    pub cpu_concave_fallbacks: u64,
    /// Explicit CPU fallback reasons; GPU tool-face work still runs for these.
    pub cpu_fallback_reasons: BTreeMap<String, u64>,
    /// Native driver, compiler, capacity or numerical failures.
    pub cuda_failures: u64,
    /// First native failure, also returned by check().
    pub last_failure: Option<String>,
}

#[derive(Default)]
struct Counters {
    arrangements: AtomicU64,
    tiles: AtomicU64,
    triples: AtomicU64,
    surviving: AtomicU64,
    candidates: AtomicU64,
    readback: AtomicU64,
    scratch: AtomicU64,
    width_hits: AtomicU64,
    concave: AtomicU64,
    failures: AtomicU64,
}

/// Run-owned CUDA service using the selected device's primary context.
/// GPU submissions use persistent bounded buffers; host topology is concurrent.
pub struct GpuSolid {
    #[cfg(feature = "cuda")]
    runtime: cuda::Runtime,
    counters: Counters,
    failure: Mutex<Option<String>>,
    #[cfg(feature = "cuda")]
    widths: Mutex<VecDeque<WidthEntry>>,
}

#[cfg(feature = "cuda")]
struct WidthEntry {
    key: Vec<u64>,
    width: Option<f64>,
}

impl std::fmt::Debug for GpuSolid {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("GpuSolid")
            .field("diagnostics", &self.diagnostics())
            .finish_non_exhaustive()
    }
}

impl GpuSolid {
    /// Compile the production-convention f64 solid kernels on the policy device.
    /// # Errors
    /// Returns CUDA initialization/NVRTC failure or missing-feature error.
    pub fn new_cuda(ordinal: usize) -> Result<Arc<Self>, String> {
        #[cfg(feature = "cuda")]
        {
            let runtime = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                cuda::Runtime::new(ordinal)
            }))
            .map_err(|payload| {
                let detail = payload
                    .downcast_ref::<String>()
                    .map(String::as_str)
                    .or_else(|| payload.downcast_ref::<&str>().copied())
                    .unwrap_or("CUDA/NVRTC dynamic-loader panic");
                format!("CUDA solid initialization failed: {detail}")
            })??;
            Ok(Arc::new(Self {
                runtime,
                counters: Counters::default(),
                failure: Mutex::default(),
                widths: Mutex::default(),
            }))
        }
        #[cfg(not(feature = "cuda"))]
        {
            let _ = ordinal;
            Err("CUDA solid geometry requires the pleochroma-ai cuda feature".into())
        }
    }

    /// Share one arrangement and each face ring across mesh and metric consumers.
    /// # Errors
    /// Returns and latches native CUDA/capacity failures. Invalid physical solids
    /// are returned as SolidStatus::Unbounded/Degenerate without a runtime error.
    pub fn build_and_measure(
        &self,
        planes: &[(DVec3, f64)],
        tools: &[ToolPrimitive],
    ) -> Result<SolidResult, String> {
        self.check()?;
        #[cfg(feature = "cuda")]
        let result = self.build_inner(planes, tools);
        #[cfg(not(feature = "cuda"))]
        let result = {
            let _ = (planes, tools);
            Err("CUDA solid feature is unavailable".into())
        };
        self.latch(result)
    }

    /// Axis width with production normalization, feasibility and positive-volume
    /// validity rules. To match optical fan absorption, pass f32-normalized fan
    /// planes widened to f64 and negate their d offsets, exactly as render_setup.
    /// # Errors
    /// Returns and latches native CUDA/capacity failures.
    pub fn measure_width(&self, planes: &[(DVec3, f64)]) -> Result<Option<f64>, String> {
        self.check()?;
        #[cfg(feature = "cuda")]
        let result = self.width_inner(planes);
        #[cfg(not(feature = "cuda"))]
        let result = {
            let _ = planes;
            Err("CUDA solid feature is unavailable".into())
        };
        self.latch(result)
    }

    /// Every feasible real-plane triple, in production lexicographic order.
    /// Uses the requested extent as a normalization floor; preserves duplicate
    /// plane indices because meet-network capture depends on their provenance.
    /// # Errors
    /// Returns and latches native failures or bounded output-capacity overflow.
    pub fn feasible_plane_triples(
        &self,
        planes: &[(DVec3, f64)],
        scale_floor: f64,
    ) -> Result<Option<Vec<([usize; 3], DVec3)>>, String> {
        self.check()?;
        #[cfg(feature = "cuda")]
        let result = self.triples_inner(planes, scale_floor);
        #[cfg(not(feature = "cuda"))]
        let result = {
            let _ = (planes, scale_floor);
            Err("CUDA solid feature is unavailable".into())
        };
        self.latch(result)
    }

    /// Propagate the first native failure to the training/evaluation owner.
    /// # Errors
    /// Returns the first latched driver/numerical error or lock failure.
    pub fn check(&self) -> Result<(), String> {
        self.failure
            .lock()
            .map_err(|e| e.to_string())?
            .as_ref()
            .map_or(Ok(()), |error| Err(error.clone()))
    }

    /// Read stable counters and explicit CPU fallback reasons.
    #[must_use]
    pub fn diagnostics(&self) -> SolidDiagnostics {
        let c = &self.counters;
        let concave = c.concave.load(Ordering::Relaxed);
        let mut reasons = BTreeMap::new();
        if concave > 0 {
            reasons.insert(
                "dynamic_concave_polygon_splitting_and_edge_visibility".into(),
                concave,
            );
        }
        let d = SolidDiagnostics {
            cuda_arrangements: c.arrangements.load(Ordering::Relaxed),
            cuda_tiles: c.tiles.load(Ordering::Relaxed),
            candidate_triples: c.triples.load(Ordering::Relaxed),
            surviving_triples: c.surviving.load(Ordering::Relaxed),
            feasible_candidates: c.candidates.load(Ordering::Relaxed),
            readback_bytes: c.readback.load(Ordering::Relaxed),
            peak_scratch_bytes: c.scratch.load(Ordering::Relaxed),
            width_cache_hits: c.width_hits.load(Ordering::Relaxed),
            cpu_concave_fallbacks: concave,
            cpu_fallback_reasons: reasons,
            cuda_failures: c.failures.load(Ordering::Relaxed),
            last_failure: self.failure.lock().ok().and_then(|failure| failure.clone()),
            ..SolidDiagnostics::default()
        };
        #[cfg(feature = "cuda")]
        let d = {
            let mut d = d;
            let clips = &self.runtime.clips;
            d.cuda_tool_face_batches = clips.batches.load(Ordering::Relaxed);
            d.cuda_tool_faces = clips.polygons.load(Ordering::Relaxed);
            d.tool_face_cache_hits = clips.cache_hits.load(Ordering::Relaxed);
            d.readback_bytes += clips.readback.load(Ordering::Relaxed);
            d.peak_scratch_bytes += clips.scratch_bytes.load(Ordering::Relaxed);
            d
        };
        d
    }

    fn latch<T>(&self, result: Result<T, String>) -> Result<T, String> {
        if let Err(error) = &result {
            self.counters.failures.fetch_add(1, Ordering::Relaxed);
            if let Ok(mut failure) = self.failure.lock()
                && failure.is_none()
            {
                *failure = Some(error.clone());
            }
        }
        result
    }

    #[cfg(feature = "cuda")]
    fn arrange(
        &self,
        planes: &[(DVec3, f64)],
    ) -> Result<Result<topology::Arrangement, SolidStatus>, String> {
        let deduped = normalize::dedup_planes(planes);
        let origin = normalize::dedup_origin_indices(planes, &deduped);
        let max = deduped
            .iter()
            .map(|&(_, m)| m.abs())
            .fold(0.0_f64, |acc, v| {
                if acc.is_nan() || v.is_nan() {
                    f64::NAN
                } else {
                    acc.max(v)
                }
            });
        let scale = normalize::pow2_scale_norm(max);
        let deduped: Vec<_> = deduped.into_iter().map(|(n, m)| (n, m / scale)).collect();
        let enumeration = self.runtime.enumerate(&deduped)?;
        let c = &self.counters;
        let w = &enumeration.work;
        c.arrangements.fetch_add(1, Ordering::Relaxed);
        c.tiles.fetch_add(w.tiles, Ordering::Relaxed);
        c.triples.fetch_add(w.triples, Ordering::Relaxed);
        c.surviving.fetch_add(w.surviving, Ordering::Relaxed);
        c.candidates.fetch_add(w.candidates, Ordering::Relaxed);
        c.readback.fetch_add(w.readback_bytes, Ordering::Relaxed);
        c.scratch.fetch_max(w.scratch_bytes, Ordering::Relaxed);
        if let Some(escaping) = enumeration.escaping {
            let mut escaping: Vec<_> = escaping.into_iter().map(|i| origin[i]).collect();
            escaping.sort_unstable();
            escaping.dedup();
            return Ok(Err(SolidStatus::Unbounded { escaping }));
        }
        if enumeration.verts.len() < 4 {
            return Ok(Err(SolidStatus::Degenerate {
                vertex_count: enumeration.verts.len(),
                volume: None,
            }));
        }
        Ok(Ok(topology::Arrangement {
            deduped,
            origin,
            scale,
            verts: enumeration.verts,
        }))
    }

    #[cfg(feature = "cuda")]
    fn triples_inner(
        &self,
        planes: &[(DVec3, f64)],
        scale_floor: f64,
    ) -> Result<Option<Vec<([usize; 3], DVec3)>>, String> {
        let floor = if scale_floor.is_finite() {
            scale_floor
        } else {
            0.0
        };
        let max = planes
            .iter()
            .map(|&(_, m)| m.abs())
            .fold(0.0_f64, |acc, v| {
                if acc.is_nan() || v.is_nan() {
                    f64::NAN
                } else {
                    acc.max(v)
                }
            });
        let scale = normalize::pow2_scale_norm(max.max(floor));
        let normalized: Vec<_> = planes.iter().map(|&(n, m)| (n, m / scale)).collect();
        let enumeration = self.runtime.triples(&normalized)?;
        let c = &self.counters;
        let w = &enumeration.work;
        c.arrangements.fetch_add(1, Ordering::Relaxed);
        c.tiles.fetch_add(w.tiles, Ordering::Relaxed);
        c.triples.fetch_add(w.triples, Ordering::Relaxed);
        c.surviving.fetch_add(w.surviving, Ordering::Relaxed);
        c.candidates.fetch_add(w.candidates, Ordering::Relaxed);
        c.readback.fetch_add(w.readback_bytes, Ordering::Relaxed);
        c.scratch.fetch_max(w.scratch_bytes, Ordering::Relaxed);
        if enumeration.escaping.is_some() {
            return Ok(None);
        }
        Ok(Some(
            enumeration
                .triples
                .into_iter()
                .map(|(t, v)| (t, v * scale))
                .collect(),
        ))
    }

    #[cfg(feature = "cuda")]
    fn build_inner(
        &self,
        planes: &[(DVec3, f64)],
        tools: &[ToolPrimitive],
    ) -> Result<SolidResult, String> {
        let arr = match self.arrange(planes)? {
            Ok(arr) => arr,
            Err(status) => {
                self.cache_width(planes, None);
                return Ok(SolidResult {
                    status,
                    metrics: None,
                    vertices: Vec::new(),
                });
            }
        };
        let rings = topology::face_rings(&arr);
        let measured = topology::measure_from_arrangement(&arr, &rings);
        let (mut metrics, vertices) = measured.map_or((None, Vec::new()), |(m, v)| (Some(m), v));
        let planar_width = metrics.as_ref().map(|m| m.width_axis);
        let mut status = topology::mesh_from_arrangement(&arr, &rings);
        if !tools.is_empty()
            && let SolidStatus::Closed(mesh) = &status
        {
            self.counters.concave.fetch_add(1, Ordering::Relaxed);
            status = concave::build(planes, tools, mesh, &self.runtime)?;
            if let (Some(m), SolidStatus::Closed(mesh)) = (&mut metrics, &status) {
                m.volume = pleochroma::geometry::stone_metrics::mesh_volume(mesh);
            }
        }
        if !matches!(status, SolidStatus::Closed(_)) {
            metrics = None;
        }
        self.cache_width(planes, planar_width);
        Ok(SolidResult {
            status,
            metrics,
            vertices,
        })
    }

    #[cfg(feature = "cuda")]
    fn width_inner(&self, planes: &[(DVec3, f64)]) -> Result<Option<f64>, String> {
        let key = plane_key(planes);
        if let Some(width) = self
            .widths
            .lock()
            .map_err(|e| e.to_string())?
            .iter()
            .find_map(|entry| (entry.key == key).then_some(entry.width))
        {
            self.counters.width_hits.fetch_add(1, Ordering::Relaxed);
            return Ok(width);
        }
        let width = match self.arrange(planes)? {
            Err(_) => None,
            Ok(arr) => {
                let rings = topology::face_rings(&arr);
                topology::measure_from_arrangement(&arr, &rings).map(|(m, _)| m.width_axis)
            }
        };
        self.cache_width(planes, width);
        Ok(width)
    }

    #[cfg(feature = "cuda")]
    fn cache_width(&self, planes: &[(DVec3, f64)], width: Option<f64>) {
        if let Ok(mut cache) = self.widths.lock() {
            let key = plane_key(planes);
            if let Some(existing) = cache.iter_mut().find(|entry| entry.key == key) {
                existing.width = width;
                return;
            }
            if cache.len() == 4 {
                cache.pop_front();
            }
            cache.push_back(WidthEntry { key, width });
        }
    }
}

#[cfg(feature = "cuda")]
fn plane_key(planes: &[(DVec3, f64)]) -> Vec<u64> {
    planes
        .iter()
        .flat_map(|&(n, m)| [n.x.to_bits(), n.y.to_bits(), n.z.to_bits(), m.to_bits()])
        .collect()
}
